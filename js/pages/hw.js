  function pair(ax, ay, wrongHints) {
    return function (v) {
      var a = UI.parseNumbers(v.replace(/[()]/g, " "));
      if (a.length !== 2 || a.some(isNaN)) return "Нужно два числа через точку с запятой: x; y";
      if (Math.abs(a[0] - ax) < 1e-6 && Math.abs(a[1] - ay) < 1e-6) return true;
      var hit = (wrongHints || []).filter(function (w) { return Math.abs(a[0] - w[0]) < 1e-6 && Math.abs(a[1] - w[1]) < 1e-6; })[0];
      return hit ? hit[2] : false;
    };
  }

